// Writes the enums the API exchanges from openapi/openapi.json: one module per enum in src/api/generated/enums/, with
// the member names the API writes next to the numbers (x-enum-varnames, see EnumNamesSchemaFilter), and
// src/api/generated/enums.ts, which re-exports them all. Run by `npm run api:types` after openapi-typescript; the output
// is not edited by hand.
//   node scripts/generate-enums.mjs
//
// One module each because the bundler places whole modules: in a single file, the enums that only a screen loaded apart
// used still went into the first visit with those the first screen needs (Fase 30C). Importing from enums.ts is the
// same as importing from the enum's module.
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';

const document = JSON.parse(await readFile(new URL('../openapi/openapi.json', import.meta.url), 'utf8'));
const schemas = document.components?.schemas ?? {};
const identifier = /^[A-Za-z_$][\w$]*$/;

const header = [
  '// Generated by scripts/generate-enums.mjs from openapi/openapi.json (npm run api:types): do not edit.',
  '// The API exchanges these enums as numbers; the names are the server\'s.',
].join('\n');

const enums = [];
for (const name of Object.keys(schemas).sort()) {
  const schema = schemas[name];
  const names = schema['x-enum-varnames'];
  if (!Array.isArray(schema.enum) || !Array.isArray(names)) continue;
  if (names.length !== schema.enum.length || !names.every((key) => identifier.test(key))
      || !schema.enum.every((value) => Number.isInteger(value))) {
    throw new Error(`${name}: x-enum-varnames does not name each numeric value.`);
  }

  // The zero of a [Flags] enum (None) is not a value anyone picks, and a combination is any number.
  const flags = schema['x-enum-flags'] === true;
  const entries = schema.enum
    .map((value, index) => [names[index], value])
    .filter(([, value]) => !(flags && value === 0));
  enums.push([name, [
    `export const ${name} = {`,
    ...entries.map(([key, value]) => `  ${key}: ${value},`),
    '} as const;',
    flags ? `export type ${name} = number;` : `export type ${name} = (typeof ${name})[keyof typeof ${name}];`,
  ].join('\n')]);
}

// A fresh folder: an enum the API no longer exchanges leaves no module behind.
const folder = new URL('../src/api/generated/enums/', import.meta.url);
await rm(folder, { recursive: true, force: true });
await mkdir(folder, { recursive: true });
await Promise.all(enums.map(([name, block]) => writeFile(new URL(`${name}.ts`, folder), `${header}\n\n${block}\n`)));

const index = enums.map(([name]) => `export { ${name} } from './enums/${name}';`);
await writeFile(new URL('../src/api/generated/enums.ts', import.meta.url), `${header}\n\n${index.join('\n')}\n`);
console.log(`src/api/generated/enums actualizado (${enums.length} enums).`);
