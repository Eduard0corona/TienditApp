public class CreateOrderCommandValidator : AbstractValidator<CreateOrderCommand>
{
    public const string PlatformPaymentMessage = "El pago «Plataforma» se registra solo, al indicar que cobró la plataforma.";
    public const string PlatformNoPhoneMessage = "Un pedido de plataforma no guarda el teléfono del cliente: la app no lo comparte.";
    public const string PlatformNoTableMessage = "Un pedido de plataforma no lleva mesa ni cuenta abierta.";
    public const string PlatformWithConnectionMessage = "Un pedido de plataforma se registra con conexión.";
    public const string PlatformAlreadyChargedMessage = "La plataforma ya cobró este pedido: no registres pagos.";
    public const string PlatformFieldsOnlyForPlatformsMessage =
        "El folio de la app y quién cobró solo van en pedidos de Rappi, Uber Eats o DiDi Food.";
    public const string DeliveryNoTableMessage = "Un pedido a domicilio no lleva mesa: la dirección dice a dónde va.";
    public const string DeliveryWithConnectionMessage = "Un pedido a domicilio se registra con conexión: su envío sale de las zonas.";
    public const string AppointmentSaleMessage =
        "La venta de una cita la registra el negocio en el mostrador: sin plataforma, mesa, cuenta abierta ni envío.";
    public const string AppointmentWithConnectionMessage = "La venta de una cita se registra con conexión: la cita se revisa al cobrar.";
    public const string AppointmentNotFoundMessage = "La cita no existe.";
    public const string CreditWithConnectionMessage = "Una venta fiada se registra con conexión: el límite del cliente se revisa al venderla.";
    public const string CustomerBalanceSaleMessage = "El saldo a favor se usa en una venta del negocio en el mostrador.";
    public const string CustomerBalanceWithConnectionMessage =
        "El saldo a favor se usa con conexión: lo que le queda al cliente se revisa al cobrar.";

    public CreateOrderCommandValidator()
    {
        RuleFor(x => x.CustomerName).MaximumLength(200);
        RuleFor(x => x.CustomerPhone).MaximumLength(50);
        RuleFor(x => x.TableNumber).MaximumLength(50);
        RuleFor(x => x.OrderType).IsInEnum();
        // Online orders come from the public menu, not from the business's screens.
        RuleFor(x => x.Channel).IsInEnum().NotEqual(OrderChannel.Online)
            .WithMessage(OrderChannelRules.InvalidChannelMessage);
        RuleFor(x => x.Items).NotEmpty().WithMessage("La orden debe tener al menos un artículo.");
        RuleFor(x => x.Items.Count)
            .LessThanOrEqualTo(OrderLimits.MaxItemsPerOrder)
            .WithMessage($"Una orden puede tener como máximo {OrderLimits.MaxItemsPerOrder} lineas.");
        RuleForEach(x => x.Items).SetValidator(new CreateOrderItemDtoValidator());
        RuleFor(x => x.ServiceDetail!.Pieces.Count)
            .LessThanOrEqualTo(OrderLimits.MaxServicePiecesPerOrder)
            .When(x => x.ServiceDetail is not null)
            .WithMessage($"Una orden puede tener como máximo {OrderLimits.MaxServicePiecesPerOrder} piezas.");

        RuleFor(x => x.Payments)
            .Empty()
            .When(x => !x.CreatedByBusiness)
            .WithMessage("Solo el negocio registra pagos al crear una venta.");
        RuleFor(x => x.Payments.Count)
            .LessThanOrEqualTo(OrderLimits.MaxPaymentsPerSale)
            .WithMessage($"Una venta admite como máximo {OrderLimits.MaxPaymentsPerSale} pagos.");
        RuleFor(x => x.IdempotencyKey)
            .NotEqual(Guid.Empty)
            .When(x => x.IdempotencyKey.HasValue)
            .WithMessage("La clave de la venta no es válida.");
        RuleFor(x => x.CapturedOfflineAt)
            .Null()
            .When(x => !x.IdempotencyKey.HasValue)
            .WithMessage("Una venta capturada sin conexión debe traer su clave.");
        RuleForEach(x => x.Payments).ChildRules(payment =>
        {
            // Stored with 2 decimals, like every payment (see AddOrderPaymentCommand).
            payment.RuleFor(p => p.Amount).GreaterThan(0).PrecisionScale(18, 2, ignoreTrailingZeros: true);
            payment.RuleFor(p => p.Method).IsInEnum();
            // The order of a delivery platform records the platform's payment by itself, never the client.
            payment.RuleFor(p => p.Method).NotEqual(OrderPaymentMethod.Platform).WithMessage(PlatformPaymentMessage);
            // «En línea» is what a customer paid in Mercado Pago from the online menu (Fase 24I), never a sale's payment.
            payment.RuleFor(p => p.Method).NotEqual(OrderPaymentMethod.Online)
                .WithMessage(OrderPaymentMethodRules.OnlineOnlyOnCreationMessage);
            payment.RuleFor(p => p.EvidenceUrl).MaximumLength(1000);
            payment.RuleFor(p => p.Reference).MaximumLength(120);
            payment.RuleFor(p => p.Notes).MaximumLength(1000);
            payment.RuleFor(p => p.Tip).GreaterThanOrEqualTo(0).PrecisionScale(18, 2, ignoreTrailingZeros: true);
            payment.RuleFor(p => p.CashReceived!.Value).GreaterThan(0).PrecisionScale(18, 2, ignoreTrailingZeros: true)
                .When(p => p.CashReceived.HasValue).WithName(nameof(CreateOrderPaymentDto.CashReceived));
            payment.RuleFor(p => p.CashReceived).Null().When(p => p.Method != OrderPaymentMethod.Cash)
                .WithMessage(OrderPayment.CashReceivedOnlyForCashMessage);
            payment.RuleFor(p => p.CashReceived!.Value).GreaterThanOrEqualTo(p => p.Amount + p.Tip)
                .When(p => p.CashReceived.HasValue && p.Method == OrderPaymentMethod.Cash)
                .WithName(nameof(CreateOrderPaymentDto.CashReceived))
                .WithMessage(OrderPayment.CashReceivedShortMessage);
            // What the customer left in their favor before (Fase 26D): the sale, without a tip or a voucher.
            payment.RuleFor(p => p.Tip).Equal(0).When(p => p.Method == OrderPaymentMethod.CustomerBalance)
                .WithMessage(OrderPaymentMethodRules.CustomerBalanceNoTipMessage);
            payment.RuleFor(p => p.EvidenceUrl).Null().When(p => p.Method == OrderPaymentMethod.CustomerBalance)
                .WithMessage(PayCustomerAccountCommandHandler.BalanceWithoutEvidenceMessage);
        });
        // Paid with the balance in the customer's favor (Fase 26D): a sale the business makes at the counter, to a customer
        // with their phone (the balance is their account's), with connection, since what they have is checked when it is
        // charged; never an order of a platform.
        When(x => x.Payments.Any(p => p.Method == OrderPaymentMethod.CustomerBalance), () =>
        {
            RuleFor(x => x.CreatedByBusiness).Equal(true).WithMessage(CustomerBalanceSaleMessage);
            RuleFor(x => x.Channel).Must(channel => !OrderChannelRules.IsDeliveryPlatform(channel))
                .WithMessage(CustomerBalanceSaleMessage);
            RuleFor(x => x.CapturedOfflineAt).Null().WithMessage(CustomerBalanceWithConnectionMessage);
            RuleFor(x => x).Must(x => x.CustomerId.HasValue || !string.IsNullOrWhiteSpace(x.CustomerPhone))
                .WithMessage(OrderPaymentMethodRules.CustomerBalanceNeedsPhoneMessage);
        });
        RuleFor(x => x.ExpectedTotal)
            .GreaterThanOrEqualTo(0)
            .PrecisionScale(18, 2, ignoreTrailingZeros: true)
            .When(x => x.ExpectedTotal.HasValue);

        When(x => x.OpenTab, () =>
        {
            RuleFor(x => x.OrderType).Equal(OrderType.Retail)
                .WithMessage("Una cuenta abierta es de consumo; los servicios no se abren como cuenta.");
            RuleFor(x => x.CreatedByBusiness).Equal(true).WithMessage("Solo el negocio abre cuentas.");
            RuleFor(x => x)
                .Must(x => x.DiningTableId.HasValue || !string.IsNullOrWhiteSpace(x.TableNumber) || !string.IsNullOrWhiteSpace(x.CustomerName))
                .WithMessage("Elige la mesa o escribe a nombre de quién va la cuenta.");
        });
        RuleFor(x => x.DiningTableId).Null().When(x => !x.OpenTab)
            .WithMessage("La mesa se indica al abrir una cuenta.");

        When(x => x.OrderType == OrderType.Service && !x.CreatedByBusiness, () =>
        {
            RuleFor(x => x.ServiceDetail).NotNull().WithMessage("El detalle del servicio es obligatorio.");
            RuleFor(x => x.ServiceDetail!.Priority).InclusiveBetween(1, 5);
            RuleFor(x => x.ServiceDetail!.IntakeNotes).MaximumLength(2000);
            RuleFor(x => x.ServiceDetail!.DeliveryNotes).MaximumLength(2000);
        });

        // Rappi, Uber Eats and DiDi Food: the business registers, with its folio, an order the platform's app already
        // took. The app shares neither the customer nor their phone, the courier takes it (no table or tab), and what
        // the platform charged is recorded by the order itself (Order.RegisterPlatformOrder), never by the client.
        When(x => OrderChannelRules.IsDeliveryPlatform(x.Channel), () =>
        {
            RuleFor(x => x.ExternalOrderNumber).Cascade(CascadeMode.Stop)
                .NotEmpty().WithMessage(PlatformOrderNumber.RequiredMessage)
                .Must(number => PlatformOrderNumber.TryNormalize(number, out _)).WithMessage(PlatformOrderNumber.InvalidMessage);
            RuleFor(x => x.CollectedBy).IsInEnum();
            RuleFor(x => x.CustomerPhone).Empty().WithMessage(PlatformNoPhoneMessage);
            RuleFor(x => x.CustomerId).Null().WithMessage(PlatformOrderRules.NoCustomerMessage);
            RuleFor(x => x.TableNumber).Empty().WithMessage(PlatformNoTableMessage);
            RuleFor(x => x.OpenTab).Equal(false).WithMessage(PlatformNoTableMessage);
            RuleFor(x => x.DiningTableId).Null().WithMessage(PlatformNoTableMessage);
            RuleFor(x => x.OrderType).Equal(OrderType.Retail).WithMessage(PlatformOrderRules.OnlyProductsMessage);
            RuleFor(x => x.ServiceDetail).Null().WithMessage(PlatformOrderRules.OnlyProductsMessage);
            RuleFor(x => x.CreatedByBusiness).Equal(true).WithMessage(PlatformOrderRules.RegisteredByBusinessMessage);
            // A repeated folio is checked against today's orders, and a queued sale would reach them late.
            RuleFor(x => x.CapturedOfflineAt).Null().WithMessage(PlatformWithConnectionMessage);
            RuleFor(x => x.Payments).Empty()
                .When(x => (x.CollectedBy ?? PlatformCollectedBy.Platform) == PlatformCollectedBy.Platform)
                .WithMessage(PlatformAlreadyChargedMessage);
            RuleForEach(x => x.Payments).ChildRules(payment =>
                payment.RuleFor(p => p.Tip).Must(tip => tip <= 0).WithMessage(PlatformOrderRules.NoTipMessage));
        });
        // Home delivery (Fase 22C): products the business sends to an address, never a tab, a table or a service, and never
        // an order of a platform, whose courier takes it.
        When(x => x.Delivery is not null, () =>
        {
            RuleFor(x => x.Delivery!).SetValidator(new OrderDeliveryInputValidator());
            RuleFor(x => x.Channel).Must(channel => !OrderChannelRules.IsDeliveryPlatform(channel))
                .WithMessage(HomeDeliveryRules.NotForPlatformsMessage);
            RuleFor(x => x.OpenTab).Equal(false).WithMessage(HomeDeliveryRules.NotForTabsMessage);
            RuleFor(x => x.DiningTableId).Null().WithMessage(HomeDeliveryRules.NotForTabsMessage);
            RuleFor(x => x.TableNumber).Empty().WithMessage(DeliveryNoTableMessage);
            RuleFor(x => x.OrderType).Equal(OrderType.Retail).WithMessage(HomeDeliveryRules.OnlyProductsMessage);
            RuleFor(x => x.ServiceDetail).Null().WithMessage(HomeDeliveryRules.OnlyProductsMessage);
            RuleFor(x => x.CapturedOfflineAt).Null().WithMessage(DeliveryWithConnectionMessage);
        });
        // The sale of an appointment of the agenda (Fase 22E): the business charges it at the counter, with connection.
        When(x => x.AppointmentId is not null, () =>
        {
            RuleFor(x => x.AppointmentId).NotEqual(Guid.Empty).WithMessage(AppointmentNotFoundMessage);
            RuleFor(x => x.CreatedByBusiness).Equal(true).WithMessage(AppointmentSaleMessage);
            RuleFor(x => x.Channel).Must(channel => !OrderChannelRules.IsDeliveryPlatform(channel)).WithMessage(AppointmentSaleMessage);
            RuleFor(x => x.OpenTab).Equal(false).WithMessage(AppointmentSaleMessage);
            RuleFor(x => x.DiningTableId).Null().WithMessage(AppointmentSaleMessage);
            RuleFor(x => x.Delivery).Null().WithMessage(AppointmentSaleMessage);
            RuleFor(x => x.CapturedOfflineAt).Null().WithMessage(AppointmentWithConnectionMessage);
        });
        // On credit (Fase 26A): a counter sale of the business to a customer with their phone, never a tab, an order to an
        // address or one of a platform, and with connection, since the customer's limit is checked when it is sold.
        When(x => x.OnCredit, () =>
        {
            RuleFor(x => x.CreatedByBusiness).Equal(true).WithMessage(Order.CreditOnlyCounterSaleMessage);
            RuleFor(x => x.Channel).Must(channel => !OrderChannelRules.IsDeliveryPlatform(channel))
                .WithMessage(Order.CreditOnlyCounterSaleMessage);
            RuleFor(x => x.OpenTab).Equal(false).WithMessage(Order.CreditOnlyCounterSaleMessage);
            RuleFor(x => x.DiningTableId).Null().WithMessage(Order.CreditOnlyCounterSaleMessage);
            RuleFor(x => x.Delivery).Null().WithMessage(Order.CreditOnlyCounterSaleMessage);
            RuleFor(x => x.CapturedOfflineAt).Null().WithMessage(CreditWithConnectionMessage);
            RuleFor(x => x).Must(x => x.CustomerId.HasValue || !string.IsNullOrWhiteSpace(x.CustomerPhone))
                .WithMessage(Order.CreditNeedsCustomerMessage);
        });
        When(x => !OrderChannelRules.IsDeliveryPlatform(x.Channel), () =>
        {
            RuleFor(x => x.ExternalOrderNumber).Empty().WithMessage(PlatformFieldsOnlyForPlatformsMessage);
            RuleFor(x => x.CollectedBy).Null().WithMessage(PlatformFieldsOnlyForPlatformsMessage);
            RuleFor(x => x.ConfirmPossibleDuplicate).Equal(false).WithMessage(PlatformFieldsOnlyForPlatformsMessage);
        });
    }
}

public class CreateOrderCommandHandler : IRequestHandler<CreateOrderCommand, Result<OrderDto>>
{
    private const string WalkInCustomerName = "Público en general";

    private readonly IApplicationDbContext _context;
    private readonly ICurrentTenantService _tenantService;
    private readonly ICurrentUserService _currentUserService;
    private readonly ICustomerLookupService _customerLookupService;
    private readonly IDateTimeProvider _dateTimeProvider;
    private readonly IPhoneNormalizationService _phoneNormalizationService;
    private readonly IOrderInventoryService _orderInventoryService;
    private readonly IOrderCashService _orderCashService;
    private readonly IFolioGenerator _folios;
    private readonly ICustomerCreditLock _creditLock;

    public CreateOrderCommandHandler(
        IApplicationDbContext context,
        ICurrentTenantService tenantService,
        ICurrentUserService currentUserService,
        ICustomerLookupService customerLookupService,
        IDateTimeProvider dateTimeProvider,
        IPhoneNormalizationService phoneNormalizationService,
        IOrderInventoryService orderInventoryService,
        IOrderCashService orderCashService,
        IFolioGenerator folios,
        ICustomerCreditLock creditLock)
    {
        _context = context;
        _tenantService = tenantService;
        _currentUserService = currentUserService;
        _customerLookupService = customerLookupService;
        _dateTimeProvider = dateTimeProvider;
        _phoneNormalizationService = phoneNormalizationService;
        _orderInventoryService = orderInventoryService;
        _orderCashService = orderCashService;
        _folios = folios;
        _creditLock = creditLock;
    }

    public async Task<Result<OrderDto>> Handle(CreateOrderCommand request, CancellationToken cancellationToken)
    {
        // 1. The same key again (a retry or a sale sent after the connection came back): the sale already exists.
        if (request.IdempotencyKey is { } key && await ExistingSaleAsync(key, cancellationToken) is { } existing)
            return Result.Success(existing);

        // One clock reading for the whole sale: an order of a delivery platform and its «Plataforma» payment share it.
        var now = _dateTimeProvider.UtcNow;

        // 2. A sale captured without connection.
        if (request.CapturedOfflineAt is { } capturedAt)
        {
            if (capturedAt > now.AddMinutes(5))
                return Result.Failure<OrderDto>("La hora de captura de la venta está en el futuro: revisa el reloj del dispositivo.");
            if (capturedAt < now.AddDays(-OrderLimits.MaxOfflineSaleAgeDays))
                return Result.Failure<OrderDto>($"La venta se capturó hace más de {OrderLimits.MaxOfflineSaleAgeDays} días: regístrala de nuevo.");
        }

        // 3. The business and its modules.
        var tenant = await _context.Tenants
            .IgnoreQueryFilters()
            .FirstOrDefaultAsync(t => t.Id == _tenantService.TenantId, cancellationToken)
            ?? throw new EntityNotFoundException("Tenant", _tenantService.TenantId);

        var tenantCapabilities = await TenantCapabilityRules.ResolveCapabilitiesAsync(
            _context,
            _tenantService.TenantId,
            cancellationToken);
        if (!TenantCapabilityRules.CanCreateOrderType(tenantCapabilities, request.OrderType))
        {
            var typeLabel = request.OrderType == OrderType.Service ? "servicios" : "ventas retail";
            return Result.Failure<OrderDto>(
                $"El negocio no tiene habilitado el módulo requerido para crear órdenes de {typeLabel}.");
        }

        // 4. An order of Rappi, Uber Eats or DiDi Food: the platform must be active in the business, whose terms the
        // order copies.
        var isPlatform = OrderChannelRules.IsDeliveryPlatform(request.Channel);
        DeliveryPlatformSetting? platformSetting = null;
        PlatformOrderNumber? platformNumber = null;
        if (isPlatform)
        {
            platformSetting = await PlatformOrderPlacement.LoadActiveSettingAsync(
                _context, _tenantService.TenantId, request.Channel, cancellationToken);
            if (platformSetting is null)
                return Result.Failure<OrderDto>(PlatformOrderErrors.NotActive(request.Channel));
            platformNumber = PlatformOrderNumber.From(request.ExternalOrderNumber);
        }

        string? customerName = request.CustomerName;
        string? customerPhone = isPlatform ? null : request.CustomerPhone;
        var isPublicGeneralCustomer = false;
        CustomerLookupResult? linkedCustomer = null;

        // 5. The customer. The app of a delivery platform shares neither the customer nor their phone: its order only
        // carries the name for the bag.
        if (!isPlatform)
        {
            if (request.CustomerId.HasValue)
            {
                var legacyCustomer = await _context.Customers
                    .FirstOrDefaultAsync(c => c.Id == request.CustomerId.Value, cancellationToken);

                if (legacyCustomer is null)
                    return Result.Failure<OrderDto>("El cliente seleccionado no existe.");

                customerName ??= legacyCustomer.Name;
                customerPhone ??= legacyCustomer.Phone;
                isPublicGeneralCustomer = legacyCustomer.IsPublicGeneral;
            }

            // The phone links the order to a customer (history, claims, notifications). A counter sale to the
            // general public may skip it; a named customer or an order placed by the customer may not.
            if (!string.IsNullOrWhiteSpace(customerPhone))
            {
                if (!_phoneNormalizationService.TryNormalizeToE164(
                        customerPhone,
                        CustomerPhoneOwnershipRules.DefaultCountry,
                        out var phoneNormalized))
                {
                    return Result.Failure<OrderDto>(PhoneNumberRules.InvalidPhoneMessage);
                }

                linkedCustomer = await _customerLookupService.ResolveForOrderAsync(
                    _tenantService.TenantId,
                    phoneNormalized,
                    customerName,
                    CustomerPhoneOwnershipRules.DefaultCountry,
                    cancellationToken);
            }
            else if (!request.CreatedByBusiness)
            {
                return Result.Failure<OrderDto>("Se requiere el teléfono del cliente para crear la orden.");
            }
            else if (request.CustomerId.HasValue && !isPublicGeneralCustomer)
            {
                return Result.Failure<OrderDto>("El cliente seleccionado no tiene teléfono. Captura uno para continuar.");
            }
        }

        // 6. The branch.
        var branch = await BranchRules.ResolveForSaleAsync(
            _context,
            _tenantService.TenantId,
            request.BranchId,
            Guid.TryParse(_currentUserService.UserId, out var cashierId) ? cashierId : null,
            cancellationToken);
        if (branch.IsFailure)
            return Result.Failure<OrderDto>(branch.Error!);

        var salesSettings = await TenantSalesSettings.ReadAsync(_context, _tenantService.TenantId, cancellationToken);
        var tenantZone = TenantDateTimeResolver.Resolve(salesSettings.TimeZone);
        var localTimeOfDay = TenantDateTimeResolver.GetLocalTimeOfDay(now, tenantZone);

        // 7. The order.
        var order = new Order(
            tenantId: _tenantService.TenantId,
            customerUserId: linkedCustomer?.CustomerUserId,
            temporaryCustomerId: linkedCustomer?.TemporaryCustomerId,
            createdByBusiness: request.CreatedByBusiness,
            orderNumber: Order.NumberNotAssigned,
            businessType: tenant.BusinessType,
            orderType: request.OrderType,
            customerName: ResolveCustomerName(customerName, linkedCustomer, customerPhone),
            customerPhone: isPlatform ? null : linkedCustomer?.PhoneNormalized,
            customerNotes: request.CustomerNotes,
            tableNumber: isPlatform ? null : request.TableNumber,
            pricesIncludeTax: salesSettings.PricesIncludeTax,
            channel: request.Channel,
            branchId: branch.Value);

        // 8. The lines. The platform's app already took the order, whatever the hours of each product here (a product
        // the business turned off is still refused), and charged the prices the business set in it.
        var checklistCandidates = new List<(Product Product, CreateOrderItemDto Item)>();
        var lineBuilder = new OrderLineBuilder(localTimeOfDay, salesSettings.DefaultTaxRate, channel: request.Channel);
        var products = await OrderCatalog.LoadProductsAsync(_context.Products, request.Items, cancellationToken, request.Channel);

        foreach (var itemDto in request.Items)
        {
            var product = products[itemDto.ProductId];
            if (!request.CreatedByBusiness && !OrderProductClassifier.MatchesOrderType(request.OrderType, product.Unit))
            {
                var expectedLabel = request.OrderType == OrderType.Service ? "servicio" : "producto";
                return Result.Failure<OrderDto>(
                    $"El item '{product.Name}' no corresponde al tipo de orden '{expectedLabel}'.");
            }

            // An order of a delivery platform is food or goods the courier takes, never a service of the business.
            if (isPlatform && OrderProductClassifier.IsServiceUnit(product.Unit))
                return Result.Failure<OrderDto>(PlatformOrderRules.OnlyProductsMessage);

            var built = lineBuilder.Build(product, itemDto);
            if (built.IsFailure)
                return Result.Failure<OrderDto>(built.Error!);

            order.AddItem(built.Value.Line);
            if (built.Value.IsTrackableService)
                checklistCandidates.Add((product, itemDto));
        }
        var quantitiesByProduct = lineBuilder.QuantitiesByProduct;

        if (request.OpenTab)
        {
            var tabError = await OpenTabAsync(order, request, tenantCapabilities, cancellationToken);
            if (tabError is not null)
                return Result.Failure<OrderDto>(tabError);
        }

        var serviceDetailError = OrderPlacement.ApplyServiceDetail(order, request.ServiceDetail, now);
        if (serviceDetailError is not null)
            return Result.Failure<OrderDto>(serviceDetailError);
        var piecesError = OrderPlacement.AddServicePieces(
            order,
            request.ServiceDetail,
            checklistCandidates,
            quantitiesByProduct.Keys.ToHashSet());
        if (piecesError is not null)
            return Result.Failure<OrderDto>(piecesError);

        // 8b. To the customer's address: the zone's minimum and fee, on the products, before any status or payment.
        if (request.Delivery is not null)
        {
            var deliveryError = await HomeDeliveryPlacement.ArrangeAsync(
                _context, order, request.Delivery, salesSettings.DefaultTaxRate, cancellationToken);
            if (deliveryError is not null)
                return Result.Failure<OrderDto>(deliveryError);
        }

        // 8c. The appointment it charges: done with the sale, and its visit charge on the services, before any status or
        // payment.
        if (request.AppointmentId is { } appointmentId)
        {
            var appointmentError = await AppointmentSalePlacement.ChargeAsync(
                _context, order, appointmentId, salesSettings.DefaultTaxRate, cancellationToken);
            if (appointmentError is not null)
                return Result.Failure<OrderDto>(appointmentError);
        }

        // 9. The status the team starts it with.
        if (request.CreatedByBusiness)
            OrderPlacement.ApplyBusinessDefaultStatus(order, _currentUserService.UserName);

        // 10. The total the customer saw and the payments.
        if (request.ExpectedTotal.HasValue && request.ExpectedTotal.Value != order.Total)
        {
            return Result.Failure<OrderDto>(
                $"El total de la venta es {OrderStatusLabels.FormatMoney(order.Total)} y no " +
                $"{OrderStatusLabels.FormatMoney(request.ExpectedTotal.Value)}: algun precio cambio. " +
                "Revisa la venta antes de cobrar.");
        }

        if (request.Payments.Sum(p => p.Amount) > order.Total)
            return Result.Failure<OrderDto>("Los pagos suman mas que el total de la venta.");

        // 11. The same folio of the same platform again today: short folios repeat, so the business confirms instead
        // of a unique index refusing a real order. A retry with the same key never gets here (step 1).
        if (isPlatform && !request.ConfirmPossibleDuplicate
            && await PlatformOrderPlacement.HasSameDayDuplicateAsync(
                _context, _tenantService.TenantId, request.Channel, platformNumber!, now, tenantZone, cancellationToken))
        {
            return Result.Failure<OrderDto>(PlatformOrderErrors.PossibleDuplicate);
        }

        // 11b. On credit: what the payments leave must fit in what the customer may still owe. Checked inside the
        // customer's credit lock, taken before the folio's, so two sales on credit (or a sale and a payment) at once
        // count each other and locks are always taken in the same order.
        if (request.OnCredit)
        {
            var creditError = await CustomerCredit.CheckSaleAsync(
                _context,
                _creditLock,
                _phoneNormalizationService,
                _tenantService.TenantId,
                request.CustomerId,
                order.CustomerPhone,
                order.Total - request.Payments.Sum(p => p.Amount),
                cancellationToken);
            // The same sale sent twice at once: this one waited on the lock while the other was recorded, and counted it in
            // what the customer owes. The answer is the sale recorded, not a refusal of the limit.
            if (request.IdempotencyKey is { } waitedKey && await ExistingSaleAsync(waitedKey, cancellationToken) is { } recorded)
                return Result.Success(recorded);
            if (creditError is not null)
                return Result.Failure<OrderDto>(creditError);
        }

        // 11c. Paid with the balance in the customer's favor (Fase 26D): it must cover all of it, read inside the customer's
        // lock, taken before the folio's as for credit, so two sales (or a sale and a payment) at once count each other.
        var fromBalance = request.Payments.Where(p => p.Method == OrderPaymentMethod.CustomerBalance).Sum(p => p.Amount);
        string? balancePhone = null;
        Guid? balanceCustomerId = null;
        if (fromBalance > 0)
        {
            if (string.IsNullOrWhiteSpace(order.CustomerPhone))
                return Result.Failure<OrderDto>(OrderPaymentMethodRules.CustomerBalanceNeedsPhoneMessage);
            balancePhone = MessagingPhone.ToKey(order.CustomerPhone);
            await _creditLock.AcquireAsync(_tenantService.TenantId, balancePhone, cancellationToken);
            // The same sale sent twice at once: this one waited while the other used the balance. The answer is that sale.
            if (request.IdempotencyKey is { } waitedKey && await ExistingSaleAsync(waitedKey, cancellationToken) is { } recorded)
                return Result.Success(recorded);
            var balance = await CustomerBalances.OfAsync(_context, balancePhone, cancellationToken);
            if (balance <= 0)
                return Result.Failure<OrderDto>(CustomerBalances.NothingInFavorMessage);
            if (fromBalance > balance)
                return Result.Failure<OrderDto>(string.Format(CustomerBalanceEntry.NotEnoughMessage, OrderStatusLabels.FormatMoney(balance)));
            balanceCustomerId = request.CustomerId
                ?? (await CreditAccount.RecordAsync(_context, balancePhone, cancellationToken, tracked: false))?.Id;
        }

        // 12. The folio, once the checks without side effects passed: payments and supplies name the order by it.
        order.AssignNumber(await _folios.NextOrderNumberAsync(_tenantService.TenantId, cancellationToken));

        // 13. The platform's terms and amounts, copied into the order and, when the platform charged, its «Plataforma»
        // payment for the total: stamped now, at the branch's stock location, outside every drawer.
        if (isPlatform)
        {
            order.RegisterPlatformOrder(
                platformSetting!,
                platformNumber!,
                request.CollectedBy ?? PlatformCollectedBy.Platform,
                now,
                await BranchRules.StockLocationIdAsync(_context, _tenantService.TenantId, order.BranchId, cancellationToken));
        }

        // 14. What the business charged now (when the business collects an order of a platform, too): into a drawer, but
        // what the customer pays with their balance in their favor.
        if (request.Payments.Count > 0)
        {
            var registrar = new OrderPaymentRegistrar(_context, _orderCashService, _dateTimeProvider);
            foreach (var paymentDto in request.Payments)
            {
                var payment = paymentDto.Method == OrderPaymentMethod.CustomerBalance
                    // What the customer left before (Fase 26D): the sale now, outside every drawer, taken from their balance.
                    ? await registrar.ApplyCustomerBalanceAsync(
                        order, paymentDto.Amount, paymentDto.Notes, balancePhone!, balanceCustomerId,
                        _currentUserService.UserName ?? "system", cancellationToken)
                    : await registrar.RegisterAsync(
                        order,
                        new OrderPaymentInput(
                            paymentDto.Amount,
                            paymentDto.Method,
                            paymentDto.InventoryLocationId,
                            paymentDto.EvidenceUrl,
                            paymentDto.Reference,
                            paymentDto.Notes,
                            paymentDto.Tip,
                            paymentDto.CashReceived),
                        cancellationToken);
                if (payment.IsFailure)
                    return Result.Failure<OrderDto>(payment.Error!);
            }
        }

        // 14b. What is left to pay is what the customer owes: the sale is handed over as a paid one.
        if (request.OnCredit)
            order.SellOnCredit();

        // 15. A paid sale closes as at the counter (an order of a platform too: same machines, same closing).
        if (request.CreatedByBusiness)
            CounterSaleClosing.TryClose(order, salesSettings, tenantCapabilities, _currentUserService.UserName);

        // 16. A sale captured offline already happened, a customer's own order is reviewed by the business, and an
        // order of a delivery platform was already accepted in its app: only a sale the team is making now can be
        // refused for missing supplies; the others sell and warn. A tab opens with its first round, which leaves the
        // stock as it goes to the kitchen.
        var shortageHandling = request.CreatedByBusiness && request.CapturedOfflineAt is null && !isPlatform
            ? StockShortageHandling.TenantPolicy
            : StockShortageHandling.Allow;
        var shortages = order.IsOpenTab
            ? await _orderInventoryService.ApplyConsumptionForTabRoundAsync(order, 1, cancellationToken, shortageHandling)
            : await _orderInventoryService.ApplyConsumptionForOrderAsync(order, cancellationToken, shortageHandling);

        // 17. Created, in one save with everything above.
        if (request.IdempotencyKey is { } requestKey)
            order.IdentifyClientRequest(requestKey, request.CapturedOfflineAt);

        order.MarkAsCreated();
        _context.Orders.Add(order);
        try
        {
            await _context.SaveChangesAsync(cancellationToken);
        }
        catch (DbUpdateException) when (order.OpenTableId.HasValue)
        {
            // Another device opened a tab on the same table first (IX_Orders_TenantId_OpenTableId_Open).
            return Result.Failure<OrderDto>("La mesa ya tiene una cuenta abierta: agrega la ronda a esa cuenta.");
        }
        catch (DbUpdateException) when (request.IdempotencyKey is { } racedKey)
        {
            // The same sale arrived twice at once and the other request stored it first (IX_Orders_TenantId_ClientRequestId).
            // This copy is undone whole, its folio, payments and supplies included (with MARS, SQL Server keeps no
            // savepoint for the failed save), and the stored one is the answer.
            await _context.DiscardUnitOfWorkAsync(cancellationToken);
            if (await ExistingSaleAsync(racedKey, cancellationToken) is { } stored)
                return Result.Success(stored);
            throw;
        }

        var dto = order.ToDto();
        dto.ApplyStateMetadata();
        dto.StockWarnings = shortages.Select(s => s.WarningMessage()).ToList();
        return Result.Success(dto);
    }

    private async Task<OrderDto?> ExistingSaleAsync(Guid idempotencyKey, CancellationToken cancellationToken)
    {
        var order = await _context.Orders
            .AsNoTracking()
            .Include(o => o.Items).ThenInclude(i => i.Options)
            .Include(o => o.StatusHistory)
            .Include(o => o.ServiceDetail)
            .Include(o => o.PlatformDetail)
            .Include(o => o.ServicePieces)
            .Include(o => o.Payments)
            .Include(o => o.Refunds)
            .Include(o => o.WriteOffs)
            .FirstOrDefaultAsync(o => o.ClientRequestId == idempotencyKey, cancellationToken);
        if (order is null)
            return null;

        var dto = order.ToDto();
        dto.ApplyStateMetadata();
        return dto;
    }

    private async Task<string?> OpenTabAsync(
        Order order,
        CreateOrderCommand request,
        TenantCapability tenantCapabilities,
        CancellationToken cancellationToken)
    {
        if (!tenantCapabilities.HasFlag(TenantCapability.Food))
            return "Las cuentas abiertas son para negocios de comida o bebida.";

        DiningTable? table = null;
        if (request.DiningTableId is { } tableId)
        {
            table = await _context.DiningTables.FirstOrDefaultAsync(t => t.Id == tableId, cancellationToken);
            if (table is null || !table.IsActive)
                return "La mesa no existe o está desactivada.";
            if (await _context.Orders.AnyAsync(o => o.OpenTableId == tableId, cancellationToken))
                return $"La mesa {table.Name} ya tiene una cuenta abierta: agrega la ronda a esa cuenta.";
        }

        var tabName = table?.Name ?? request.TableNumber?.Trim();
        order.OpenAsTab(table?.Id, tabName, _dateTimeProvider.UtcNow, _currentUserService.UserName);
        return null;
    }

    private static string ResolveCustomerName(string? requestedName, CustomerLookupResult? linkedCustomer, string? rawPhone)
    {
        if (!string.IsNullOrWhiteSpace(requestedName))
            return requestedName.Trim();

        return linkedCustomer?.ResolvedName ?? rawPhone ?? WalkInCustomerName;
    }
