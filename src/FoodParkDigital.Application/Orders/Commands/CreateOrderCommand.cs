public class CreateOrderCommandValidator : AbstractValidator<CreateOrderCommand>
{
    public CreateOrderCommandValidator()
    {
        RuleFor(x => x.CustomerName).MaximumLength(200);
        RuleFor(x => x.CustomerPhone).MaximumLength(50);
        RuleFor(x => x.TableNumber).MaximumLength(50);
        RuleFor(x => x.OrderType).IsInEnum();
        // Online orders come from the public menu, not from the business's screens.
        RuleFor(x => x.Channel).IsInEnum().NotEqual(OrderChannel.Online)
            .WithMessage("El canal del pedido no es válido.");
        RuleFor(x => x.Items).NotEmpty().WithMessage("La orden debe tener al menos un artículo.");
        RuleFor(x => x.Items.Count)
            .LessThanOrEqualTo(OrderLimits.MaxItemsPerOrder)
            .WithMessage($"Una orden puede tener como máximo {OrderLimits.MaxItemsPerOrder} lineas.");
        RuleForEach(x => x.Items).SetValidator(new CreateOrderItemDtoValidator());
        RuleFor(x => x.ServiceDetail!.Pieces.Count)
            .LessThanOrEqualTo(OrderLimits.MaxServicePiecesPerOrder)
            .When(x => x.ServiceDetail is not null)
            .WithMessage($"Una orden puede tener como máximo {OrderLimits.MaxServicePiecesPerOrder} piezas.");

        RuleFor(x => x.Payments)
            .Empty()
            .When(x => !x.CreatedByBusiness)
            .WithMessage("Solo el negocio registra pagos al crear una venta.");
        RuleFor(x => x.Payments.Count)
            .LessThanOrEqualTo(OrderLimits.MaxPaymentsPerSale)
            .WithMessage($"Una venta admite como máximo {OrderLimits.MaxPaymentsPerSale} pagos.");
        RuleFor(x => x.IdempotencyKey)
            .NotEqual(Guid.Empty)
            .When(x => x.IdempotencyKey.HasValue)
            .WithMessage("La clave de la venta no es válida.");
        RuleFor(x => x.CapturedOfflineAt)
            .Null()
            .When(x => !x.IdempotencyKey.HasValue)
            .WithMessage("Una venta capturada sin conexión debe traer su clave.");
        RuleForEach(x => x.Payments).ChildRules(payment =>
        {
            // Stored with 2 decimals, like every payment (see AddOrderPaymentCommand).
            payment.RuleFor(p => p.Amount).GreaterThan(0).PrecisionScale(18, 2, ignoreTrailingZeros: true);
            payment.RuleFor(p => p.Method).IsInEnum();
            payment.RuleFor(p => p.EvidenceUrl).MaximumLength(1000);
            payment.RuleFor(p => p.Reference).MaximumLength(120);
            payment.RuleFor(p => p.Notes).MaximumLength(1000);
            payment.RuleFor(p => p.Tip).GreaterThanOrEqualTo(0).PrecisionScale(18, 2, ignoreTrailingZeros: true);
            payment.RuleFor(p => p.CashReceived!.Value).GreaterThan(0).PrecisionScale(18, 2, ignoreTrailingZeros: true)
                .When(p => p.CashReceived.HasValue).WithName(nameof(CreateOrderPaymentDto.CashReceived));
            payment.RuleFor(p => p.CashReceived).Null().When(p => p.Method != OrderPaymentMethod.Cash)
                .WithMessage(OrderPayment.CashReceivedOnlyForCashMessage);
            payment.RuleFor(p => p.CashReceived!.Value).GreaterThanOrEqualTo(p => p.Amount + p.Tip)
                .When(p => p.CashReceived.HasValue && p.Method == OrderPaymentMethod.Cash)
                .WithName(nameof(CreateOrderPaymentDto.CashReceived))
                .WithMessage(OrderPayment.CashReceivedShortMessage);
        });
        RuleFor(x => x.ExpectedTotal)
            .GreaterThanOrEqualTo(0)
            .PrecisionScale(18, 2, ignoreTrailingZeros: true)
            .When(x => x.ExpectedTotal.HasValue);

        When(x => x.OpenTab, () =>
        {
            RuleFor(x => x.OrderType).Equal(OrderType.Retail)
                .WithMessage("Una cuenta abierta es de consumo; los servicios no se abren como cuenta.");
            RuleFor(x => x.CreatedByBusiness).Equal(true).WithMessage("Solo el negocio abre cuentas.");
            RuleFor(x => x)
                .Must(x => x.DiningTableId.HasValue || !string.IsNullOrWhiteSpace(x.TableNumber) || !string.IsNullOrWhiteSpace(x.CustomerName))
                .WithMessage("Elige la mesa o escribe a nombre de quién va la cuenta.");
        });
        RuleFor(x => x.DiningTableId).Null().When(x => !x.OpenTab)
            .WithMessage("La mesa se indica al abrir una cuenta.");

        When(x => x.OrderType == OrderType.Service && !x.CreatedByBusiness, () =>
        {
            RuleFor(x => x.ServiceDetail).NotNull().WithMessage("El detalle del servicio es obligatorio.");
            RuleFor(x => x.ServiceDetail!.Priority).InclusiveBetween(1, 5);
            RuleFor(x => x.ServiceDetail!.IntakeNotes).MaximumLength(2000);
            RuleFor(x => x.ServiceDetail!.DeliveryNotes).MaximumLength(2000);
        });
    }
}

public class CreateOrderCommandHandler : IRequestHandler<CreateOrderCommand, Result<OrderDto>>
{
    private const string WalkInCustomerName = "Público en general";

    private readonly IApplicationDbContext _context;
    private readonly ICurrentTenantService _tenantService;
    private readonly ICurrentUserService _currentUserService;
    private readonly IMapper _mapper;
    private readonly ICustomerLookupService _customerLookupService;
    private readonly IDateTimeProvider _dateTimeProvider;
    private readonly IPhoneNormalizationService _phoneNormalizationService;
    private readonly IOrderInventoryService _orderInventoryService;
    private readonly IOrderCashService _orderCashService;
    private readonly IFolioGenerator _folios;

    public CreateOrderCommandHandler(
        IApplicationDbContext context,
        ICurrentTenantService tenantService,
        ICurrentUserService currentUserService,
        IMapper mapper,
        ICustomerLookupService customerLookupService,
        IDateTimeProvider dateTimeProvider,
        IPhoneNormalizationService phoneNormalizationService,
        IOrderInventoryService orderInventoryService,
        IOrderCashService orderCashService,
        IFolioGenerator folios)
    {
        _context = context;
        _tenantService = tenantService;
        _currentUserService = currentUserService;
        _mapper = mapper;
        _customerLookupService = customerLookupService;
        _dateTimeProvider = dateTimeProvider;
        _phoneNormalizationService = phoneNormalizationService;
        _orderInventoryService = orderInventoryService;
        _orderCashService = orderCashService;
        _folios = folios;
    }

    public async Task<Result<OrderDto>> Handle(CreateOrderCommand request, CancellationToken cancellationToken)
    {
        // The same key again (a retry or a sale sent after the connection came back): the sale already exists.
        if (request.IdempotencyKey is { } key && await ExistingSaleAsync(key, cancellationToken) is { } existing)
            return Result.Success(existing);

        if (request.CapturedOfflineAt is { } capturedAt)
        {
            var now = _dateTimeProvider.UtcNow;
            if (capturedAt > now.AddMinutes(5))
                return Result.Failure<OrderDto>("La hora de captura de la venta está en el futuro: revisa el reloj del dispositivo.");
            if (capturedAt < now.AddDays(-OrderLimits.MaxOfflineSaleAgeDays))
                return Result.Failure<OrderDto>($"La venta se capturó hace más de {OrderLimits.MaxOfflineSaleAgeDays} días: regístrala de nuevo.");
        }

        var tenant = await _context.Tenants
            .IgnoreQueryFilters()
            .FirstOrDefaultAsync(t => t.Id == _tenantService.TenantId, cancellationToken)
            ?? throw new EntityNotFoundException("Tenant", _tenantService.TenantId);

        var tenantCapabilities = await TenantCapabilityRules.ResolveCapabilitiesAsync(
            _context,
            _tenantService.TenantId,
            cancellationToken);
        if (!TenantCapabilityRules.CanCreateOrderType(tenantCapabilities, request.OrderType))
        {
            var typeLabel = request.OrderType == OrderType.Service ? "servicios" : "ventas retail";
            return Result.Failure<OrderDto>(
                $"El negocio no tiene habilitado el módulo requerido para crear órdenes de {typeLabel}.");
        }

        string? customerName = request.CustomerName;
        string? customerPhone = request.CustomerPhone;
        var isPublicGeneralCustomer = false;

        if (request.CustomerId.HasValue)
        {
            var legacyCustomer = await _context.Customers
                .FirstOrDefaultAsync(c => c.Id == request.CustomerId.Value, cancellationToken);

            if (legacyCustomer is null)
                return Result.Failure<OrderDto>("El cliente seleccionado no existe.");

            customerName ??= legacyCustomer.Name;
            customerPhone ??= legacyCustomer.Phone;
            isPublicGeneralCustomer = legacyCustomer.IsPublicGeneral;
        }

        // The phone links the order to a customer (history, claims, notifications). A counter sale to the
        // general public may skip it; a named customer or an order placed by the customer may not.
        CustomerLookupResult? linkedCustomer = null;
        if (!string.IsNullOrWhiteSpace(customerPhone))
        {
            if (!_phoneNormalizationService.TryNormalizeToE164(
                    customerPhone,
                    CustomerPhoneOwnershipRules.DefaultCountry,
                    out var phoneNormalized))
            {
                return Result.Failure<OrderDto>(PhoneNumberRules.InvalidPhoneMessage);
            }

            linkedCustomer = await _customerLookupService.ResolveForOrderAsync(
                _tenantService.TenantId,
                phoneNormalized,
                customerName,
                CustomerPhoneOwnershipRules.DefaultCountry,
                cancellationToken);
        }
        else if (!request.CreatedByBusiness)
        {
            return Result.Failure<OrderDto>("Se requiere el teléfono del cliente para crear la orden.");
        }
        else if (request.CustomerId.HasValue && !isPublicGeneralCustomer)
        {
            return Result.Failure<OrderDto>("El cliente seleccionado no tiene teléfono. Captura uno para continuar.");
        }

        var branch = await BranchRules.ResolveForSaleAsync(
            _context,
            _tenantService.TenantId,
            request.BranchId,
            Guid.TryParse(_currentUserService.UserId, out var cashierId) ? cashierId : null,
            cancellationToken);
        if (branch.IsFailure)
            return Result.Failure<OrderDto>(branch.Error!);

        var salesSettings = await TenantSalesSettings.ReadAsync(_context, _tenantService.TenantId, cancellationToken);
        var tenantZone = TenantDateTimeResolver.Resolve(salesSettings.TimeZone);
        var localTimeOfDay = TenantDateTimeResolver.GetLocalTimeOfDay(_dateTimeProvider.UtcNow, tenantZone);

        var order = new Order(
            tenantId: _tenantService.TenantId,
            customerUserId: linkedCustomer?.CustomerUserId,
            temporaryCustomerId: linkedCustomer?.TemporaryCustomerId,
            createdByBusiness: request.CreatedByBusiness,
            orderNumber: Order.NumberNotAssigned,
            businessType: tenant.BusinessType,
            orderType: request.OrderType,
            customerName: ResolveCustomerName(customerName, linkedCustomer, customerPhone),
            customerPhone: linkedCustomer?.PhoneNormalized,
            customerNotes: request.CustomerNotes,
            tableNumber: request.TableNumber,
            pricesIncludeTax: salesSettings.PricesIncludeTax,
            channel: request.Channel,
            branchId: branch.Value);
        var checklistCandidates = new List<(Product Product, CreateOrderItemDto Item)>();
        var lineBuilder = new OrderLineBuilder(localTimeOfDay, salesSettings.DefaultTaxRate);
        var products = await OrderCatalog.LoadProductsAsync(_context.Products, request.Items, cancellationToken);

        foreach (var itemDto in request.Items)
        {
            var product = products[itemDto.ProductId];
            if (!request.CreatedByBusiness && !OrderProductClassifier.MatchesOrderType(request.OrderType, product.Unit))
            {
                var expectedLabel = request.OrderType == OrderType.Service ? "servicio" : "producto";
                return Result.Failure<OrderDto>(
                    $"El item '{product.Name}' no corresponde al tipo de orden '{expectedLabel}'.");
            }

            var built = lineBuilder.Build(product, itemDto);
            if (built.IsFailure)
                return Result.Failure<OrderDto>(built.Error!);

            order.AddItem(built.Value.Line);
            if (built.Value.IsTrackableService)
                checklistCandidates.Add((product, itemDto));
        }
        var quantitiesByProduct = lineBuilder.QuantitiesByProduct;

        if (request.OpenTab)
        {
            var tabError = await OpenTabAsync(order, request, tenantCapabilities, cancellationToken);
            if (tabError is not null)
                return Result.Failure<OrderDto>(tabError);
        }

        OrderPlacement.ApplyServiceDetail(order, request.ServiceDetail, _dateTimeProvider.UtcNow);
        var piecesError = OrderPlacement.AddServicePieces(
            order,
            request.ServiceDetail,
            checklistCandidates,
            quantitiesByProduct.Keys.ToHashSet());
        if (piecesError is not null)
            return Result.Failure<OrderDto>(piecesError);

        if (request.CreatedByBusiness)
            OrderPlacement.ApplyBusinessDefaultStatus(order, _currentUserService.UserName);

        if (request.ExpectedTotal.HasValue && request.ExpectedTotal.Value != order.Total)
        {
            return Result.Failure<OrderDto>(
                $"El total de la venta es {OrderStatusLabels.FormatMoney(order.Total)} y no " +
                $"{OrderStatusLabels.FormatMoney(request.ExpectedTotal.Value)}: algun precio cambio. " +
                "Revisa la venta antes de cobrar.");
        }

        if (request.Payments.Sum(p => p.Amount) > order.Total)
            return Result.Failure<OrderDto>("Los pagos suman mas que el total de la venta.");

        // The folio, once the checks without side effects passed: payments and supplies name the order by it.
        order.AssignNumber(await _folios.NextOrderNumberAsync(_tenantService.TenantId, cancellationToken));

        if (request.Payments.Count > 0)
        {
            var registrar = new OrderPaymentRegistrar(_context, _orderCashService, _dateTimeProvider);
            foreach (var paymentDto in request.Payments)
            {
                var payment = await registrar.RegisterAsync(
                    order,
                    new OrderPaymentInput(
                        paymentDto.Amount,
                        paymentDto.Method,
                        paymentDto.InventoryLocationId,
                        paymentDto.EvidenceUrl,
                        paymentDto.Reference,
                        paymentDto.Notes,
                        paymentDto.Tip,
                        paymentDto.CashReceived),
                    cancellationToken);
                if (payment.IsFailure)
                    return Result.Failure<OrderDto>(payment.Error!);
            }
        }

        if (request.CreatedByBusiness)
            CounterSaleClosing.TryClose(order, salesSettings, tenantCapabilities, _currentUserService.UserName);

        // A sale captured offline already happened, and a customer's own order is reviewed by the business: only a
        // sale the team is making now can be refused for missing supplies.
        var shortages = await _orderInventoryService.ApplyConsumptionForOrderAsync(
            order,
            cancellationToken,
            request.CreatedByBusiness && request.CapturedOfflineAt is null ? StockShortageHandling.TenantPolicy : StockShortageHandling.Allow);

        if (request.IdempotencyKey is { } requestKey)
            order.IdentifyClientRequest(requestKey, request.CapturedOfflineAt);

        order.MarkAsCreated();
        _context.Orders.Add(order);
        try
        {
            await _context.SaveChangesAsync(cancellationToken);
        }
        catch (DbUpdateException) when (order.OpenTableId.HasValue)
        {
            // Another device opened a tab on the same table first (IX_Orders_TenantId_OpenTableId_Open).
            return Result.Failure<OrderDto>("La mesa ya tiene una cuenta abierta: agrega la ronda a esa cuenta.");
        }
        catch (DbUpdateException) when (request.IdempotencyKey is { } racedKey)
        {
            // The same sale arrived twice at once and the other request stored it first (IX_Orders_TenantId_ClientRequestId).
            _context.ChangeTracker.Clear();
            if (await ExistingSaleAsync(racedKey, cancellationToken) is { } stored)
                return Result.Success(stored);
            throw;
        }

        var dto = _mapper.Map<OrderDto>(order);
        dto.ApplyStateMetadata();
        dto.StockWarnings = shortages.Select(s => s.WarningMessage()).ToList();
        return Result.Success(dto);
    }

    private async Task<OrderDto?> ExistingSaleAsync(Guid idempotencyKey, CancellationToken cancellationToken)
    {
        var order = await _context.Orders
            .AsNoTracking()
            .Include(o => o.Items).ThenInclude(i => i.Options)
            .Include(o => o.StatusHistory)
            .Include(o => o.ServiceDetail)
            .Include(o => o.ServicePieces)
            .Include(o => o.Payments)
            .Include(o => o.Refunds)
            .FirstOrDefaultAsync(o => o.ClientRequestId == idempotencyKey, cancellationToken);
        if (order is null)
            return null;

        var dto = _mapper.Map<OrderDto>(order);
        dto.ApplyStateMetadata();
        return dto;
    }

    private async Task<string?> OpenTabAsync(
        Order order,
        CreateOrderCommand request,
        TenantCapability tenantCapabilities,
        CancellationToken cancellationToken)
    {
        if (!tenantCapabilities.HasFlag(TenantCapability.Food))
            return "Las cuentas abiertas son para negocios de comida o bebida.";

        DiningTable? table = null;
        if (request.DiningTableId is { } tableId)
        {
            table = await _context.DiningTables.FirstOrDefaultAsync(t => t.Id == tableId, cancellationToken);
            if (table is null || !table.IsActive)
                return "La mesa no existe o está desactivada.";
            if (await _context.Orders.AnyAsync(o => o.OpenTableId == tableId, cancellationToken))
                return $"La mesa {table.Name} ya tiene una cuenta abierta: agrega la ronda a esa cuenta.";
        }

        var tabName = table?.Name ?? request.TableNumber?.Trim();
        order.OpenAsTab(table?.Id, tabName, _dateTimeProvider.UtcNow, _currentUserService.UserName);
        return null;
    }

    private static string ResolveCustomerName(string? requestedName, CustomerLookupResult? linkedCustomer, string? rawPhone)
    {
        if (!string.IsNullOrWhiteSpace(requestedName))
            return requestedName.Trim();

        return linkedCustomer?.ResolvedName ?? rawPhone ?? WalkInCustomerName;
    }
}
