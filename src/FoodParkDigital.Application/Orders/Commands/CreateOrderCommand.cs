[RequiresPermission(TenantPermission.ManageOrders)]
public record CreateOrderCommand : IRequest<Result<OrderDto>>, IRequiresContentPermissions, ITransactionalRequest
{
    /// <summary>
    /// Taking an order needs ManageOrders; charging it at once, or selling it on credit, also needs ChargeOrders. The
    /// «Plataforma» payment of an order a delivery platform charged is recorded by the server, outside every drawer: nobody
    /// charges it. The sale of an appointment completes it in the agenda, so it also needs whoever books appointments
    /// (Fase 22E), as reading it does.
    /// </summary>
    public IEnumerable<TenantPermission> RequiredPermissions()
    {
        if (Payments is { Count: > 0 } || OnCredit)
            yield return TenantPermission.ChargeOrders;
        if (AppointmentId is not null)
            yield return TenantPermission.ManageAppointments;
    }

    public Guid? CustomerId { get; init; }
    public string? CustomerName { get; init; }
    public string? CustomerPhone { get; init; }
    public string? CustomerNotes { get; init; }
    public string? TableNumber { get; init; }
    public bool CreatedByBusiness { get; init; } = true;
    public OrderType OrderType { get; init; } = OrderType.Retail;
    public ServiceOrderDetailInput? ServiceDetail { get; init; }
    public List<CreateOrderItemDto> Items { get; init; } = new();
    /// <summary>Payments taken at the counter with the sale: stored with the order or not at all.</summary>
    public List<CreateOrderPaymentDto> Payments { get; init; } = new();
    /// <summary>
    /// Total shown to the customer. When it differs from the server total (a price changed meanwhile)
    /// the sale is rejected instead of charging a different amount.
    /// </summary>
    public decimal? ExpectedTotal { get; init; }
    /// <summary>
    /// Counter (default); WhatsApp, when the business takes the order from a chat; or Rappi, Uber Eats or DiDi Food, when
    /// the business registers an order that came in through the delivery platform's app.
    /// </summary>
    public OrderChannel Channel { get; init; } = OrderChannel.Counter;
    /// <summary>The folio the delivery platform's app shows for the order: only with Rappi, Uber Eats or DiDi Food.</summary>
    public string? ExternalOrderNumber { get; init; }
    /// <summary>
    /// Who charged an order of a delivery platform: the platform, in its app (when omitted), or the business, when the
    /// courier pays on pickup. Only with Rappi, Uber Eats or DiDi Food.
    /// </summary>
    public PlatformCollectedBy? CollectedBy { get; init; }
    /// <summary>
    /// The business already registered an order of the same platform with the same folio today and confirms this is
    /// another one (short folios repeat). Sent again with the same idempotency key after the possible duplicate warning.
    /// </summary>
    [System.ComponentModel.DefaultValue(false)]
    public bool ConfirmPossibleDuplicate { get; init; }
    /// <summary>
    /// Opens the order as a tab: its items are the first round sent to the kitchen, more rounds are added
    /// later and it is charged and closed when the table leaves.
    /// </summary>
    public bool OpenTab { get; init; }
    /// <summary>Table of the tab; a tab can also go by a name (TableNumber or CustomerName).</summary>
    public Guid? DiningTableId { get; init; }
    /// <summary>
    /// Branch where the sale is made (the one the device works at). When omitted: the branch of the cashier's
    /// open drawer, else the default branch.
    /// </summary>
    public Guid? BranchId { get; init; }
    /// <summary>
    /// Key generated by the device for this sale. Sending it again (a retry, or a sale captured without connection)
    /// returns the sale already created with it instead of charging twice.
    /// </summary>
    public Guid? IdempotencyKey { get; init; }
    /// <summary>When the device captured the sale without connection: at most 7 days ago, and 5 minutes ahead for clock drift.</summary>
    public DateTimeOffset? CapturedOfflineAt { get; init; }
    /// <summary>
    /// The order goes to the customer's address (Fase 22C): a zone of the business must reach the postal code and the
    /// products its minimum; what the zone charges is added to the total. Not for platforms, tabs, tables or services.
    /// </summary>
    public OrderDeliveryInput? Delivery { get; init; }
    /// <summary>
    /// The appointment of the agenda this sale charges (Fase 22E): it is done with the sale, and when it was at the
    /// customer's address the charge for the visit agreed is added to the total. Only for a sale the business makes at the
    /// counter, with connection; once per appointment, unless its sale was cancelled.
    /// </summary>
    public Guid? AppointmentId { get; init; }
    /// <summary>
    /// Sold on credit (Fase 26A): what the payments leave unpaid is what the customer owes, and the sale is handed over as
    /// a paid one. Only a counter sale of the business, with connection, to a customer the business sells to on credit
    /// whose limit takes it.
    /// </summary>
    [System.ComponentModel.DefaultValue(false)]
    public bool OnCredit { get; init; }
}

public record CreateOrderPaymentDto
{
    public decimal Amount { get; init; }
    public OrderPaymentMethod Method { get; init; }
    public Guid? InventoryLocationId { get; init; }
    public string? EvidenceUrl { get; init; }
    public string? Reference { get; init; }
    public string? Notes { get; init; }
    /// <summary>On top of the amount, for the team: not part of the sale or its total. 0 when not sent.</summary>
    [System.ComponentModel.DefaultValue(0)]
    public decimal Tip { get; init; }
    /// <summary>What the customer handed over in cash, to keep the change with the payment.</summary>
    public decimal? CashReceived { get; init; }
}

public record CreateOrderItemDto
{
    public Guid ProductId { get; init; }
    /// <summary>Whole for pieces; up to three decimals for weight, volume, length and time.</summary>
    public decimal Quantity { get; init; }
    public string? Notes { get; init; }
    /// <summary>Variants and extras chosen (ids of the product's options).</summary>
    public List<Guid> OptionIds { get; init; } = new();
}

/// <summary>Rules of a requested line, shared by sales, tab rounds and online orders.</summary>
public class CreateOrderItemDtoValidator : AbstractValidator<CreateOrderItemDto>
{
    public const int MaxOptionsPerLine = 50;

    public CreateOrderItemDtoValidator()
    {
        RuleFor(i => i.ProductId).NotEmpty();
        RuleFor(i => i.Quantity).GreaterThan(0).LessThanOrEqualTo(OrderLimits.MaxQuantityPerLine)
            .PrecisionScale(18, 3, ignoreTrailingZeros: true);
        RuleFor(i => i.Notes).MaximumLength(300);
        RuleFor(i => i.OptionIds).NotNull();
        RuleFor(i => i.OptionIds.Count).LessThanOrEqualTo(MaxOptionsPerLine).When(i => i.OptionIds is not null);
    }
}

